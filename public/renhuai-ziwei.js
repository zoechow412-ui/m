(function(){
  const stems=['甲','乙','丙','丁','戊','己','庚','辛','壬','癸'];
  const sihua={
    '甲':['廉貞','破軍','武曲','太陽'],'乙':['天機','天梁','紫微','太陰'],
    '丙':['天同','天機','文昌','廉貞'],'丁':['太陰','天同','天機','巨門'],
    '戊':['貪狼','太陰','右弼','天機'],'己':['武曲','貪狼','天梁','文曲'],
    '庚':['太陽','武曲','太陰','天同'],'辛':['巨門','太陽','文曲','文昌'],
    '壬':['天梁','紫微','左輔','武曲'],'癸':['破軍','巨門','太陰','貪狼']
  };
  const descriptions={
    '紫微':'帝王、尊貴、獨立；重視主導權及整體方向。','天機':'智慧、機變、謀略；擅長分析、學習及調整方案。','太陽':'陽剛、官貴、慷慨；適合公開承擔及照亮他人。','武曲':'財富、剛毅、果斷；重視效率、資源及可量化成果。','天同':'溫和、享福、隨緣；需要舒服環境及可持續節奏。','廉貞':'才藝、原則、桃花；創意強但要處理界線與規範。','天府':'財庫、穩重、保守；擅長管理、保存及整合資源。','太陰':'柔美、財富、內在；重視安全感、細節及深層感受。','貪狼':'欲望、桃花、多才；有探索力，但要避免分心過多。','巨門':'口舌、是非、善辯；語言是武器，也要管理誤解。','天相':'輔佐、行政、印綬；擅長協調制度及支援核心人物。','天梁':'蔭護、醫藥、長輩；重視保護、修正及長期責任。','七殺':'將星、果決、孤克；適合處理危機，但不宜長期硬撐。','破軍':'開創、變動、破壞；適合改革重整，需先計算代價。'
  };
  const palaces=['命宮','兄弟宮','夫妻宮','子女宮','財帛宮','疾厄宮','遷移宮','交友宮','官祿宮','田宅宮','福德宮','父母宮'];
  function enrich(year, chart){
    const stem=stems[((year-4)%10+10)%10], arr=sihua[stem]||[];
    const starMap={}; arr.forEach((star,i)=>starMap[star]=['化祿','化權','化科','化忌'][i]);
    const rows=(chart?.palaces||[]).slice(0,12).map((p,i)=>{
      const name=p.name||palaces[i]||'宮位';
      const stars=(p.majorStars||p.stars||[]).map(s=>s.name||s).filter(Boolean);
      const notes=stars.map(s=>`${s}${descriptions[s]?'：'+descriptions[s]:''}${starMap[s]?'（'+starMap[s]+'）':''}`);
      return `${name}：${notes.join('；')||'暫未見主星，需借對宮參看'}`;
    });
    return {stem, transforms:{'化祿':arr[0],'化權':arr[1],'化科':arr[2],'化忌':arr[3]}, rows, descriptions};
  }
  window.RenhuaiZiwei={enrich,descriptions,sihua,palaces,source:'Renhuai123/ziwei-doushu'};
})();
